import { describe, it, expect } from 'vitest'
import { formatSolution, solutionCommands, planSolution, SOLUTION_MAX, SOLUTION_STORE_MAX } from './solution-text'

describe('formatSolution', () => {
  it('writes the exact header, opening, then each command and reply', () => {
    const out = formatSolution('Cave', 'Welcome.\n', [
      { command: 'look', output: 'A cave.\n' },
      { command: 'wait', output: '' },
    ])
    expect(out).toBe('Cave — solution\n(generated by frotzsmith from 2 commands)\n\nWelcome.\n\n> look\nA cave.\n\n> wait\n')
  })
  it('handles zero commands', () => {
    expect(formatSolution('Cave', 'Hi', [])).toBe('Cave — solution\n(generated by frotzsmith from 0 commands)\n\nHi\n')
  })
})

describe('solutionCommands', () => {
  const turns = [{ command: 'north', output: 'x > y' }, { command: 'take lamp', output: 'Taken.' }]
  it('round-trips formatSolution', () => {
    expect(solutionCommands(formatSolution('T', 'open', turns))).toEqual(['north', 'take lamp'])
  })
  it('ignores > mid-line, trims, skips blanks, handles CRLF', () => {
    expect(solutionCommands('a > b\r\n>   go  \r\n> \r\n>\r\n> two\r\n')).toEqual(['go', 'two'])
  })
})

describe('planSolution', () => {
  it('accepts up to the caps', () => {
    expect(planSolution('x'.repeat(SOLUTION_MAX), 0)).toEqual({ ok: true })
  })
  it('refuses one over 1 MiB', () => {
    const r = planSolution('x'.repeat(SOLUTION_MAX + 1), 0)
    expect(r.ok).toBe(false)
  })
  it('refuses a total over 2 MiB', () => {
    // 2 MiB, not more: the store shares the ~5 MiB origin quota with source autosave.
    expect(SOLUTION_MAX).toBe(1024 * 1024)
    expect(SOLUTION_STORE_MAX).toBe(2 * 1024 * 1024)
    expect(planSolution('xx', SOLUTION_STORE_MAX - 2)).toEqual({ ok: true })
    const r = planSolution('xxx', SOLUTION_STORE_MAX - 2)
    expect(r.ok).toBe(false)
    if (!r.ok) expect(r.message).toMatch(/\.$/)
  })
})
