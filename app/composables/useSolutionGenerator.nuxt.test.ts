/// <reference types="node" />
/**
 * useSolutionGenerator — a solution is made by replaying commands from the
 * start of the game against the current build (compiling first when stale).
 *
 * Real useIde over a mocked compiler that "builds" the bundled demo.z5, and
 * a fake replay worker that runs the real headless engine (replayCore) and
 * speaks the worker's message protocol, so the runReplayController path and
 * its partial-turns-on-error extension are exercised end to end.
 */
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { ref } from 'vue'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { useSourceDocument } from './useSourceDocument'
import { useExtensions } from './useExtensions'
import { useProjectFiles } from './useProjectFiles'
import { useTestScripts } from './useTestScripts'
import { useZilProjectFiles } from './useZilProjectFiles'
import { useLanguage } from './useLanguage'
import { runReplayController, type WorkerLike } from './useReplay'
import { solutionCommands } from './solution-text'
import { runReplay } from '~/modules/inform6/engine/replayCore'
import demoSource from '~/modules/inform6/samples/demo.inf?raw'

const demoStory = new Uint8Array(readFileSync(resolve(process.cwd(), 'public/play/demo.z5')))

vi.stubGlobal('useSourceDocument', useSourceDocument)
vi.stubGlobal('useExtensions', useExtensions)
vi.stubGlobal('useProjectFiles', useProjectFiles)
vi.stubGlobal('useTestScripts', useTestScripts)
vi.stubGlobal('useZilProjectFiles', useZilProjectFiles)
vi.stubGlobal('useLanguage', useLanguage)
vi.stubGlobal('usePlayTranscript', () => ({ reset: vi.fn(), commands: ref([]), record: vi.fn() }))
vi.stubGlobal('useTranscript', () => ({ reset: vi.fn() }))
vi.stubGlobal('useMap', () => ({ reset: vi.fn() }))
vi.stubGlobal('useToast', () => ({ add: vi.fn() }))

const okBuild = () => ({
  ok: true, storyFile: demoStory.slice(), storyExt: 'z5' as const,
  diagnostics: [], rawStderr: '', ms: 1, byteLength: demoStory.length,
})
const _compile = vi.fn()
vi.stubGlobal('useCompiler', () => ({ compile: _compile }))

/** How the fake worker behaves: 'real' replays; 'error-after-1' plays one
 *  command then reports an engine error; 'hang' never answers. */
let workerMode: 'real' | 'error-after-1' | 'hang' = 'real'
const _cancels: Array<ReturnType<typeof vi.fn>> = []
vi.stubGlobal('useReplay', () => ({
  replay: (story: Uint8Array, target: 'zmachine', commands: string[], opts: { timeoutMs?: number } = {}) => {
    const mode = workerMode
    const w: WorkerLike = {
      onmessage: null,
      onerror: null,
      terminate: () => {},
      postMessage: () => {
        if (mode === 'hang') return
        void (async () => {
          if (mode === 'error-after-1') {
            const partial = await runReplay(story, target, commands.slice(0, 1))
            w.onmessage?.({ data: { type: 'error', message: 'Illegal opcode', turns: partial.turns } })
            return
          }
          const res = await runReplay(story, target, commands)
          w.onmessage?.({ data: { type: 'result', turns: res.turns, ms: res.ms } })
        })()
      },
    }
    const ctrl = runReplayController(() => w, { story, target, commands }, opts)
    const cancel = vi.fn(ctrl.cancel)
    _cancels.push(cancel)
    return { promise: ctrl.promise, cancel }
  },
}))

const { useIde } = await import('./useIde')
vi.stubGlobal('useIde', useIde)
const { useSolutionGenerator } = await import('./useSolutionGenerator')

beforeEach(() => {
  vi.clearAllMocks()
  localStorage.clear()
  useLanguage().setLanguage('i6')
  workerMode = 'real'
  _cancels.length = 0
  _compile.mockImplementation(async () => okBuild())
  useIde().loadSource(demoSource)
})

describe('useSolutionGenerator — generate', () => {
  it('compiles a stale build, then gives the opening and every command with its reply', async () => {
    const ide = useIde()
    expect(ide.buildIsCurrent.value).toBe(false)
    const commands = ['north', 'south']
    const r = await useSolutionGenerator().generate(commands)
    expect(r.ok).toBe(true)
    if (!r.ok) return
    expect(_compile).toHaveBeenCalledTimes(1)
    expect(r.note).toBeUndefined()
    expect(solutionCommands(r.text)).toEqual(commands)
    expect(r.text.startsWith('FROTZSMITH DEMO — solution\n(generated by Frotzsmith from 2 commands)\n\n')).toBe(true)
    expect(r.text).toContain('Welcome to the Frotzsmith demo!') // the opening, before the first command
    const afterNorth = r.text.split('> north')[1]!
    expect(afterNorth).toContain('Meadow')
  })

  it('does not recompile a current build; recompiles once the source changes', async () => {
    const gen = useSolutionGenerator()
    await gen.generate(['north'])
    await gen.generate(['north', 'south'])
    expect(_compile).toHaveBeenCalledTimes(1)
    useIde().source.value += '\n! an edit'
    const r = await gen.generate(['north'])
    expect(r.ok).toBe(true)
    expect(_compile).toHaveBeenCalledTimes(2)
  })

  it('a game that ends early gives the text so far with a note', async () => {
    const r = await useSolutionGenerator().generate(['quit', 'yes', 'look', 'look'])
    expect(r.ok).toBe(true)
    if (!r.ok) return
    expect(solutionCommands(r.text)).toEqual(['quit', 'yes'])
    expect(r.note).toBe('The game ended after 2 of 4 commands, so the rest were not played.')
    expect(r.text).toContain('Welcome to the Frotzsmith demo!')
  })

  it('an engine error part-way gives the text so far with a note', async () => {
    workerMode = 'error-after-1'
    const r = await useSolutionGenerator().generate(['north', 'south', 'north'])
    expect(r.ok).toBe(true)
    if (!r.ok) return
    expect(solutionCommands(r.text)).toEqual(['north'])
    expect(r.text).toContain('Meadow')
    expect(r.note).toBe('The game stopped with an error after 1 of 3 commands (Illegal opcode), so the text ends there.')
  })

  it('a build that does not compile is refused with one sentence', async () => {
    _compile.mockImplementation(async () => ({
      ok: false, storyExt: 'z5', diagnostics: [{ severity: 'error', message: 'x' }], rawStderr: '', ms: 1, byteLength: 0,
    }))
    const r = await useSolutionGenerator().generate(['north'])
    expect(r).toEqual({ ok: false, message: 'The game did not compile, so there is no solution to show; Results has the errors.' })
  })

  it('a Glulx build is refused', async () => {
    _compile.mockImplementation(async () => ({ ...okBuild(), storyExt: 'ulx' }))
    const r = await useSolutionGenerator().generate(['north'])
    expect(r).toEqual({ ok: false, message: 'Solutions need a Z-machine build, and this game compiles to Glulx.' })
  })

  it('called again before the first finishes: the latest wins, the earlier is cancelled and discarded', async () => {
    const gen = useSolutionGenerator()
    await gen.generate([]) // build once so both calls go straight to replay
    workerMode = 'hang'
    const first = gen.generate(['north'])
    await new Promise(r => setTimeout(r, 0))
    workerMode = 'real'
    const second = gen.generate(['north', 'south'])
    const [a, b] = await Promise.all([first, second])
    expect(a).toMatchObject({ ok: false, superseded: true })
    expect(_cancels.at(-2)).toHaveBeenCalled() // the first replay's worker was stopped
    expect(b.ok).toBe(true)
    if (b.ok) expect(solutionCommands(b.text)).toEqual(['north', 'south'])
  })

  it('many calls in a row (live regeneration): only the last one resolves with text', async () => {
    const gen = useSolutionGenerator()
    await gen.generate([])
    const calls = [['north'], ['north', 'south'], ['north', 'south', 'north']].map(c => gen.generate(c))
    const results = await Promise.all(calls)
    expect(results.slice(0, 2).every(r => !r.ok && r.superseded)).toBe(true)
    const last = results[2]!
    expect(last.ok).toBe(true)
    if (last.ok) expect(solutionCommands(last.text)).toEqual(['north', 'south', 'north'])
  })

  it('a different game loaded mid-replay discards the result', async () => {
    const gen = useSolutionGenerator()
    await gen.generate([])
    workerMode = 'hang'
    const pending = gen.generate(['north'])
    await new Promise(r => setTimeout(r, 0))
    useIde().loadSource('Constant Story "Other";\n')
    _cancels.at(-1)!() // a new source stops nothing by itself; settle the hung replay
    const r = await pending
    expect(r.ok).toBe(false)
  })
})
