/**
 * Pure helpers for a game's solution file: the text format and the size caps.
 * Command lines are exactly `> <command>` at line start; everything else is
 * the game's text.
 */

/** One solution may be at most 1 MiB (UTF-16 length). */
export const SOLUTION_MAX = 1024 * 1024
/** All solutions together may be at most 2 MiB (UTF-16 length). The store
 *  shares the origin's ~5 MiB localStorage with source autosave, test
 *  scripts and the rest, so it keeps well under half of it. */
export const SOLUTION_STORE_MAX = 2 * 1024 * 1024

/** The solution text: header, the opening, then each command and its reply. */
export function formatSolution(
  title: string,
  opening: string,
  turns: { command: string; output: string }[],
): string {
  const lines = [
    `${title} — solution`,
    `(generated by Frotzsmith from ${turns.length} command${turns.length === 1 ? '' : 's'})`,
    '',
    opening.trim(),
  ]
  for (const t of turns) {
    lines.push('', `> ${t.command}`)
    const out = t.output.trim()
    if (out) lines.push(out)
  }
  return lines.join('\n') + '\n'
}

/** The `> ` lines in order, trimmed, blanks skipped. */
export function solutionCommands(text: string): string[] {
  const out: string[] = []
  for (const line of text.split(/\r\n|\r|\n/)) {
    if (!line.startsWith('>')) continue
    const cmd = line.slice(1).trim()
    if (cmd) out.push(cmd)
  }
  return out
}

/** Check both caps; `otherTotal` is the length of every other game's solution. */
export function planSolution(text: string, otherTotal: number): { ok: true } | { ok: false; message: string } {
  if (text.length > SOLUTION_MAX) {
    return { ok: false, message: 'That solution is over 1 MiB, which is more than Frotzsmith keeps for one game.' }
  }
  if (text.length + otherTotal > SOLUTION_STORE_MAX) {
    return { ok: false, message: 'Frotzsmith already holds 2 MiB of solutions in this browser, so clear another game’s solution first.' }
  }
  return { ok: true }
}
